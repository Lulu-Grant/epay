  `report_type` varchar(20) NOT NULL DEFAULT 'daily',
  `period_start` datetime NOT NULL,
  `period_end` datetime NOT NULL,
  `health_level` varchar(20) NOT NULL,
  `metrics_json` longtext NOT NULL,
  `rules_json` longtext NOT NULL,
  `ai_status` tinyint(1) NOT NULL DEFAULT '0',
  `ai_provider` varchar(40) DEFAULT NULL,
  `ai_model` varchar(100) DEFAULT NULL,
  `ai_duration_ms` int(11) DEFAULT NULL,
  `ai_json` longtext DEFAULT NULL,
  `ai_error` varchar(500) DEFAULT NULL,
  `ai_attempted_at` datetime DEFAULT NULL,
  `ai_request_sha256` char(64) DEFAULT NULL,
  `ai_response_sha256` char(64) DEFAULT NULL,
  `ai_started_at` datetime DEFAULT NULL,
  `ai_completed_at` datetime DEFAULT NULL,
  `ai_retry_until` datetime DEFAULT NULL,
  `ai_next_retry_at` datetime DEFAULT NULL,
  `ai_calls` int(11) NOT NULL DEFAULT '0',
  `ai_source_rows` int(11) NOT NULL DEFAULT '0',
  `ai_sample_rows` int(11) NOT NULL DEFAULT '0',
  `ai_drilldown_rows` int(11) NOT NULL DEFAULT '0',
  `ai_payload_mode` varchar(16) NOT NULL DEFAULT 'compact',
  `ai_request_bytes` bigint(20) unsigned NOT NULL DEFAULT '0',
  `ai_response_bytes` bigint(20) unsigned NOT NULL DEFAULT '0',
  `ai_input_tokens` bigint(20) unsigned NOT NULL DEFAULT '0',
  `ai_output_tokens` bigint(20) unsigned NOT NULL DEFAULT '0',
