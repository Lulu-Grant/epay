CREATE TABLE IF NOT EXISTS `pre_health_snapshot` (
  `id` bigint(20) unsigned NOT NULL AUTO_INCREMENT,
  `snapshot_time` datetime NOT NULL,
  `period_start` datetime NOT NULL,
  `period_end` datetime NOT NULL,
  `scope_type` varchar(20) NOT NULL,
  `scope_id` varchar(32) NOT NULL DEFAULT '0',
  `metrics_json` longtext NOT NULL,
  `metrics_version` varchar(20) NOT NULL,
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_snapshot_scope` (`snapshot_time`,`scope_type`,`scope_id`,`metrics_version`),
  KEY `idx_scope_time` (`scope_type`,`scope_id`,`snapshot_time`),
  KEY `idx_period` (`period_start`,`period_end`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `pre_health_report` (
